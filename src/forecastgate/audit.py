"""Data audit and run provenance.

`data_audit.md` is deterministic: the same archive and code produce the same bytes, so a
regenerated audit can be compared with the committed one. Anything that varies between
runs (commit, clock, library versions) goes to `provenance.json` instead.
"""

from __future__ import annotations

import json
import os
import platform
import sys
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path

import pandas as pd

from forecastgate.config import Settings
from forecastgate.ingest import IngestResult
from forecastgate.panel import Panel
from forecastgate.universe import eligible_products

AUDIT_FILE = "data_audit.md"
PROVENANCE_FILE = "provenance.json"
PACKAGES = ("pandas", "pandera", "numpy", "pyarrow", "openpyxl")


def _ts(value: pd.Timestamp) -> str:
    return f"{value:%Y-%m-%d %H:%M}"


def _day(value: pd.Timestamp) -> str:
    return f"{value:%Y-%m-%d}"


def render_data_audit(
    data: IngestResult,
    panel: Panel,
    *,
    cutoff: pd.Timestamp,
    universe: list[str],
    settings: Settings,
) -> str:
    sales_quantity = int(data.sales["Quantity"].sum())
    identical = data.exclusions["identical_row"]
    identical_share = identical.quantity / (sales_quantity + identical.quantity)
    observed = panel.frame["quantity"].dropna()
    zero_share = float((observed == 0).mean())

    lines = [
        "# Data audit",
        "",
        "Generated by `uv run forecastgate reproduce`. Deterministic content only: run",
        f"provenance (commit, time, library versions) is in `{PROVENANCE_FILE}`.",
        "",
        "## Source",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Source | `{settings.source.name}` |",
        f"| Archive SHA-256 | `{data.data_hash}` |",
    ]
    for sheet in data.sheets:
        span = f"{_ts(sheet.first)} to {_ts(sheet.last)}"
        lines.append(f"| Sheet `{sheet.name}` | {sheet.rows:,} rows, {span} |")
    lines += [
        "",
        "## Sheet overlap",
        "",
        f"Sheet 2 starts at {_ts(data.overlap_boundary)}. The {data.overlap_rows:,} rows both",
        "sheets cover are an exact multiset match (checked; a mismatch rejects the file). Sheet 1",
        "supplies rows before the boundary and sheet 2 everything from it, so shared rows count",
        "once.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Rows after the overlap rule | {len(data.transactions):,} |",
        f"| Coverage | {_ts(data.data_start)} to {_ts(data.data_end)} |",
        "",
        "## Stock code normalisation",
        "",
        "Codes are stripped of whitespace and upper-cased before any exclusion, because",
        "lower-case codes (for example `15056p`) sell alongside upper-case twins, usually with",
        "the same description. The overlap check above runs on the original codes.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Rows whose code changed | {data.codes.rows_changed:,} |",
        f"| Distinct codes before / after | {data.codes.raw_codes:,} / "
        f"{data.codes.normalised_codes:,} |",
        "",
        "## Exclusions",
        "",
        "Applied in this order; each row is counted under the first rule that removes it.",
        "",
        "| Rule | Rows | Quantity |",
        "|---|---:|---:|",
    ]
    for rule, excluded in data.exclusions.items():
        lines.append(f"| `{rule}` | {excluded.rows:,} | {excluded.quantity:,} |")
    lines += [
        f"| **Sales rows kept** | **{len(data.sales):,}** | **{sales_quantity:,}** |",
        "",
        "Dropping identical rows is an assumption, not a proven defect: they may be repeated",
        f"invoice lines. They hold {identical_share:.2%} of sales quantity before removal.",
        "",
        f"Sales rows without a Customer ID: {int(data.sales['Customer ID'].isna().sum()):,}",
        "(allowed; customer identity is not used).",
        "",
        "### Codes excluded as non-product",
        "",
        "Rule: a product code is five digits with an optional letter suffix. Excluded codes,",
        "with rows among those reaching this rule:",
        "",
        "| Code | Rows |",
        "|---|---:|",
    ]
    for code, rows in data.non_product_codes.items():
        lines.append(f"| `{code}` | {rows:,} |")
    lines += [
        "",
        "## Weekly panel",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Complete weeks | {len(panel.weeks)}, {_day(panel.weeks[0])} to "
        f"{_day(panel.weeks[-1])} (Mondays) |",
        "| Zero-transaction weeks (assumed closures, treated as missing) | "
        + (", ".join(_day(w) for w in panel.zero_transaction_weeks) or "none")
        + " |",
        f"| Products with a recorded sale | {len(panel.first_sale_week):,} |",
        f"| Panel rows (product-weeks from first sale) | {len(panel.frame):,} |",
        f"| Observed product-weeks with 0 recorded sales | {zero_share:.2%} |",
        "",
        "## Universe at the publication cutoff",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Cutoff week | {_day(cutoff)} |",
        f"| Rule | first sale at least {settings.min_history_weeks} weeks before the cutoff; "
        f"top {settings.universe_size} by quantity over {settings.ranking_window_weeks} weeks |",
        f"| Eligible products | {len(eligible_products(panel, cutoff, settings)):,} |",
        f"| Selected products | {len(universe):,} |",
        "",
    ]
    return "\n".join(lines)


def provenance(
    settings: Settings, git_sha: str, extra: dict[str, object] | None = None
) -> dict[str, object]:
    return {
        **(extra or {}),
        "source": settings.source.name,
        "data_hash": settings.source.sha256,
        "git_sha": git_sha,
        "generated_at": f"{datetime.now(UTC):%Y-%m-%dT%H:%M:%SZ}",
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "packages": {name: version(name) for name in PACKAGES},
    }


def write_text(path: Path, text: str) -> None:
    """Write via a temporary file and atomic replace, with LF newlines."""
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + ".part")
    partial.write_bytes(text.encode("utf-8"))
    os.replace(partial, path)


def write_report(
    reports_dir: Path,
    name: str,
    content: str,
    settings: Settings,
    git_sha: str,
    *,
    extra: dict[str, object] | None = None,
) -> Path:
    """Write a deterministic report and record its run provenance under its file name.

    `provenance.json` maps each report file to the run that last wrote it, so writing one
    report never erases another report's provenance.
    """
    path = reports_dir / name
    write_text(path, content)
    provenance_path = reports_dir / PROVENANCE_FILE
    try:
        existing = json.loads(provenance_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        existing = {}
    # A file from before per-report provenance holds a single run's fields at top level.
    records = existing if isinstance(existing, dict) and "git_sha" not in existing else {}
    records[name] = provenance(settings, git_sha, extra)
    write_text(provenance_path, json.dumps(records, indent=2, sort_keys=True) + "\n")
    return path
